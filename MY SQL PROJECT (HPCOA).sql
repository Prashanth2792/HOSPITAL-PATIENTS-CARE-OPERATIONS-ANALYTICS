-- 4.1 Understand Patient and Appointment Demand --
-- ● Compare appointment volume across cities. --
SELECT P.CITY, 
COUNT(A.APPOINTMENT_ID) AS APPOINTMENT_VOLUME
FROM PATIENTS P
JOIN APPOINTMENTS A
ON P.PATIENT_ID = A.PATIENT_ID
GROUP BY P.CITY
ORDER BY APPOINTMENT_VOLUME
DESC;

-- ● Compare appointments across service types and priorities. --
SELECT SERVICE_TYPE,PRIORITY,
COUNT(APPOINTMENT_ID) AS APPOINTMENT_VOLUME
FROM APPOINTMENTS
GROUP BY  SERVICE_TYPE,PRIORITY
ORDER BY APPOINTMENT_VOLUME 
DESC;

-- ● Examine appointment volume over time. -- 
SELECT  YEAR(APPOINTMENT_DATE) AS YEAR,
MONTH(APPOINTMENT_DATE) AS MONTH,
COUNT(APPOINTMENT_ID) AS APPOINTMENT_VOLUME
FROM APPOINTMENTS
GROUP BY YEAR(APPOINTMENT_DATE),MONTH(APPOINTMENT_DATE)
ORDER BY YEAR,MONTH;

-- ● Compare estimated appointment value across patient types. --
SELECT P.PATIENT_TYPE,SUM(A.ESTIMATED_COST) AS TOTAL_ESTIMATED_VALUE
FROM PATIENTS P
JOIN APPOINTMENTS A
ON P.PATIENT_ID = A.PATIENT_ID
GROUP BY P.PATIENT_TYPE
ORDER BY TOTAL_ESTIMATED_VALUE 
DESC;

-- ● Examine booking channels and their contribution to demand. --
SELECT BOOKING_CHANEL,COUNT(APPOINTMENT_ID) AS APPOINTMENT_VOLUME
FROM APPOINTMENTS
GROUP BY BOOKING_CHANEL
ORDER BY APPOINTMENT_VOLUME
DESC;


