-- Identify which treatment statuses occur most frequently.
SELECT STATUS,
COUNT(TREATMENT_ID) AS TREATMENT_COUNT
FROM TREATMENTS
GROUP BY STATUS
ORDER BY TREATMENT_COUNT 
DESC;

-- ● Compare waiting time for appointments with multiple attempts.
-- Determine whether appointments requiring multiple treatment attempts have different waiting times.
SELECT CASE WHEN TREATMENT_ATTEMPT > 1 THEN 'Multiple Attempts' ELSE 'Single Attempt' END AS ATTEMPT_GROUP,
COUNT(TREATMENT_ID) AS TREATMENT_COUNT,
ROUND(AVG(WAITING_TIME_MIN), 2) AS AVG_WAITING_TIME
FROM TREATMENTS
GROUP BY CASE WHEN TREATMENT_ATTEMPT > 1 THEN 'Multiple Attempts' ELSE 'Single Attempt' END
ORDER BY AVG_WAITING_TIME 
DESC;

