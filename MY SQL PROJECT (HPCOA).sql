-- ● Examine treatment duration and waiting time. --
-- Understand how long treatments take and how long patients wait.
SELECT STATUS,
COUNT(TREATMENT_ID) AS TREATMENT_COUNT,
ROUND(AVG(TREATMENT_DURATION_MIN), 2) AS AVG_DURATION_MIN,
ROUND(AVG(WAITING_TIME_MIN), 2) AS AVG_WAITING_MIN
FROM TREATMENTS
GROUP BY STATUS
ORDER BY TREATMENT_COUNT 
DESC;

-- ● Compare Completed, Cancelled, No-Show, Rescheduled, and In Progress outcomes. --
-- Count how many treatments fall into each outcome/status.
SELECT STATUS,
COUNT(TREATMENT_ID) AS TREATMENT_COUNT
FROM TREATMENTS
GROUP BY STATUS
ORDER BY TREATMENT_COUNT 
DESC;

-- ● Identify areas with higher treatment activity or poorer outcomes. --
-- Here, area = city, because CITY is stored in the PATIENTS table.
SELECT P.CITY,
COUNT(T.TREATMENT_ID) AS TOTAL_TREATMENTS,
SUM(CASE WHEN T.STATUS = 'Completed' THEN 1 ELSE 0 END) AS COMPLETED,
SUM(CASE WHEN T.STATUS = 'Cancelled' THEN 1 ELSE 0 END) AS CANCELLED,
SUM(CASE WHEN T.STATUS = 'Rescheduled' THEN 1 ELSE 0 END) AS RESCHEDULED,
SUM(CASE WHEN T.STATUS = 'No-Show' THEN 1 ELSE 0 END) AS NO_SHOW
FROM PATIENTS P
JOIN APPOINTMENTS A
ON P.PATIENT_ID = A.PATIENT_ID
JOIN TREATMENTS T
ON A.APPOINTMENT_ID = T.APPOINTMENT_ID
GROUP BY P.CITY
ORDER BY TOTAL_TREATMENTS 
DESC;

-- ● Compare treatment performance over time. --
-- Understand whether treatment activity and performance are changing month by month.
SELECT DATE_FORMAT(ACTUAL_TREATMENT_DATE, '%Y-%m') AS TREATMENT_MONTH,
COUNT(TREATMENT_ID) AS TOTAL_TREATMENTS,
ROUND(AVG(TREATMENT_DURATION_MIN), 2) AS AVG_TREATMENT_DURATION,
ROUND(AVG(WAITING_TIME_MIN), 2) AS AVG_WAITING_TIME
FROM TREATMENTS
GROUP BY DATE_FORMAT(ACTUAL_TREATMENT_DATE, '%Y-%m')
ORDER BY TREATMENT_MONTH;


