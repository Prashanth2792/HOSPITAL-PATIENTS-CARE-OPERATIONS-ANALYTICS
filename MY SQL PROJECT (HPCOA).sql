-- 1.Management wants to identify patients who have booked multiple appointments. Which table and columns are needed? --
-- Tables and columns needed; 1. PATIENTS:PATIENT_ID,PATIENT_NAME 2. APPOINTMENTS: PATIENT_ID,APPOINTMENT_ID
-- Querry;
SELECT P.PATIENT_ID,P.PATIENT_NAME,
COUNT(A.APPOINTMENT_ID) AS TOTAL_APPOINTMENTS
FROM PATIENTS P
JOIN APPOINTMENTS A
ON P.PATIENT_ID = A.PATIENT_ID
GROUP BY P.PATIENT_ID,p.PATIENT_NAME
HAVING COUNT(A.APPOINTMENT_ID) > 1;

-- 2. Operations wants to identify appointments that required more than one treatment attempt. Where is this information found? --
-- Tables and columns needed; 1. TREATMENTS:TREATMENT_ID,APPOINTMENT_ID,TREATMENT_ATTEMPT
-- Querry;
SELECT APPOINTMENT_ID,TREATMENT_ID,TREATMENT_ATTEMPT
FROM TREATMENTS
WHERE TREATMENT_ATTEMPT > 1
ORDER BY TREATMENT_ATTEMPT;

-- 3. Patient Services wants to compare General, Corporate, and Insurance patients based on appointment activity. Which tables must be connected? --
-- Ans:Tables and columns needed; 1. PATIENTS:PATIENT_ID,PATIENT_TYPE 2. APPOINTMENTS: PATIENT_ID,APPOINTMENT_ID
SELECT P.PATIENT_TYPE,
COUNT(A.APPOINTMENT_ID) AS TOTAL_APPOINTMENTS
FROM PATIENTS P
JOIN APPOINTMENTS A
    ON P.PATIENT_ID = A.PATIENT_ID
GROUP BY P.PATIENT_TYPE
ORDER BY TOTAL_APPOINTMENTS;

-- 4. Operations wants to compare service types based on treatment duration and waiting time. Which tables are required? --
-- Ans: Tables and columns needed; 1. TREATMENTS:APPOINTMENT_ID,TREATMENT_DURATION_MIN,WAITING_TIME_MIN 2. APPOINTMENTS: SERVICE_TYPE,APPOINTMENT_ID
SELECT A.SERVICE_TYPE,
ROUND(AVG(T.TREATMENT_DURATION_MIN), 2) AS AVG_TREATMENT_DURATION,
ROUND(AVG(T.WAITING_TIME_MIN), 2) AS AVG_WAITING_TIME
FROM APPOINTMENTS A
JOIN TREATMENTS T
ON A.APPOINTMENT_ID = T.APPOINTMENT_ID
GROUP BY A.SERVICE_TYPE
ORDER BY AVG_TREATMENT_DURATION DESC;

-- 5. The team wants to identify which doctors handled treatments and examine their recorded ratings. What information is needed? --
-- Ans:Tables and columns needed; 1. TREATMENTS:DOCTER_ID,TREATMENT_ID 2. DOCTERS:DOCTER_ID,DOCTER_NAME,RATING
SELECT D.DOCTER_ID,D.DOCTER_NAME,D.RATING,
COUNT(T.TREATMENT_ID) AS TOTAL_TREATMENTS
FROM DOCTERS D
JOIN TREATMENTS T
ON D.DOCTER_ID = T.DOCTER_ID
GROUP BY D.DOCTER_ID,D.DOCTER_NAME,D.RATING
ORDER BY TOTAL_TREATMENTS DESC;

-- 6. Operations wants to understand whether different room/equipment types are used for different service types. Which tables and columns are required? --
-- Ans: Tables and columns needed; 1. TREATMENTS:APPOINTMENT_ID,ROOM_ID 2. APPOINTMENTS:APPOINTMENT_ID,SERVICE_TYPE 3.ROOMS: ROOM_ID,ROOM_TYPE,EQUIPMENT_TYPE
SELECT A.SERVICE_TYPE,R.ROOM_TYPE,R.EQUIPMENT_TYPE,
COUNT(T.TREATMENT_ID) TT
FROM APPOINTMENTS A
JOIN TREATMENTS T 
ON A.APPOINTMENT_ID = T.APPOINTMENT_ID
JOIN ROOMS R 
ON T.ROOM_ID = R.ROOM_ID
GROUP BY  A.SERVICE_TYPE,R.ROOM_TYPE,R.EQUIPMENT_TYPE
ORDER BY TT DESC;

-- 7. Management wants to compare treatment performance across cities. What information must be connected? --
-- ANS:  Tables and columns needed; 1. TREATMENTS:APPOINTMENT_ID,STATUS,TREATMENT_DURATION_MIN,WAITITNG_TIME_MIN 2. PATIENTS: PATIENT_ID,CITY 3.APPOINTMENTS: PATIENT_ID,APPOINTMENT_ID
 SELECT P.CITY,
COUNT(t.TREATMENT_ID) AS TOTAL_TREATMENTS,
ROUND(AVG(t.TREATMENT_DURATION_MIN), 2) AS AVG_TREATMENT_DURATION,
ROUND(AVG(t.WAITING_TIME_MIN), 2) AS AVG_WAITING_TIME
FROM PATIENTS P
JOIN APPOINTMENTS A
ON P.PATIENT_ID = A.PATIENT_ID
JOIN TREATMENTS T
ON A.APPOINTMENT_ID = T.APPOINTMENT_ID
GROUP BY P.CITY
ORDER BY TOTAL_TREATMENTS DESC;

-- 8. Operations wants to investigate whether higher-priority appointments have longer waiting times or different outcomes. What information is needed? --
-- ANS: Tables and columns needed; 1. TREATMENTS:APPOINTMENT_ID,STATUS,WAITITNG_TIME_MIN 2. APPOINTMENTS: PATIENT_ID,PRIORITY
SELECT A.PRIORITY,
COUNT(T.TREATMENT_ID) AS TOTAL_TREATMENTS,
ROUND(AVG(T.WAITING_TIME_MIN), 2) AS AVG_WAITING_TIME,
T.STATUS, COUNT(*) AS STATUS_COUNT
FROM APPOINTMENTS A
JOIN TREATMENTS T
ON A.APPOINTMENT_ID = T.APPOINTMENT_ID
GROUP BY A.PRIORITY,T.STATUS
ORDER BY A.PRIORITY,STATUS_COUNT DESC;

-- 9. Management wants to understand whether treatment outcomes differ across service types. What tables and fields should be combined? --
-- ANS: Tables and columns needed; 1. TREATMENTS:APPOINTMENT_ID,STATUS 2. APPOINTMENTS: APPOINTMENT_ID, SERVICE_TYPE
SELECT A.SERVICE_TYPE,T.STATUS,
COUNT(T.TREATMENT_ID) AS TREATMENT_COUNT
FROM APPOINTMENTS A
JOIN TREATMENTS T
ON A.APPOINTMENT_ID = T.APPOINTMENT_ID
GROUP BY A.SERVICE_TYPE,T.STATUS
ORDER BY A.SERVICE_TYPE,TREATMENT_COUNT DESC;

-- 10. The Patient Services team wants to connect each patient to their appointments and treatment outcomes. What relationships are required? --
-- ANS: Tables and columns needed; 1. TREATMENTS:APPOINTMENT_ID,STATUS 2. PATIENTS: PATIENT_ID,PATIENT_NAME 3.APPOINTMENTS: STATUS,APPOINTMENT_ID
SELECT P.PATIENT_ID,P.PATIENT_NAME,A.APPOINTMENT_ID,T.TREATMENT_ID,T.STATUS AS TREATMENT_OUTCOME
FROM PATIENTS P
JOIN APPOINTMENTS A
ON P.PATIENT_ID = A.PATIENT_ID
JOIN TREATMENTS T
ON A.APPOINTMENT_ID = T.APPOINTMENT_ID
ORDER BY P.PATIENT_ID, A.APPOINTMENT_ID;


