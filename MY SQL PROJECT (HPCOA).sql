# CREATING TABLES
#TABLE 1. {PATIENTS}
CREATE TABLE PATIENTS
(
PATIENT_ID VARCHAR(20) PRIMARY KEY,
PATIENT_NAME VARCHAR(100) NOT NULL,
AGE INT NOT NULL,
GENDER VARCHAR(10) NOT NULL,
CITY VARCHAR(50),
PATIENT_TYPE VARCHAR(20),
PREFERRED_TIME_SLOT VARCHAR(20) NOT NULL,
REGISTRATION_DATE DATE NOT NULL
);
SELECT * FROM PATIENTS;

# TABLE 2. {ROOMS}
CREATE TABLE ROOMS
(
ROOM_ID VARCHAR(10) PRIMARY KEY,
ROOM_TYPE VARCHAR(30) NOT NULL,
FLOOR INT NOT NULL,
EQUIPMENT_TYPE VARCHAR(50) NOT NULL,
CAPACITY INT,
LAST_MAINTAINANCE_DATE DATE NOT NULL,
IS_AVAILABLE VARCHAR(3) NOT NULL
);
SELECT * FROM ROOMS;

# TABLE 3. {DOCTERS}
CREATE TABLE DOCTERS
(
DOCTER_ID VARCHAR(10) PRIMARY KEY,
DOCTER_NAME VARCHAR(100) NOT NULL,
SPECIALITY VARCHAR(50) NOT NULL,
HIRE_DATE DATE,
RATING DECIMAL(3,2) NOT NULL,
EMPLOYEMENT_TYPE VARCHAR(20) NOT NULL,
IS_ACTIVE VARCHAR(3) NOT NULL
);
SELECT * FROM DOCTERS;

# TABLE 4. {APPOINTMENTS}
CREATE TABLE APPOINTMENTS
(
APPOINTMENT_ID VARCHAR(20) PRIMARY KEY,
PATIENT_ID VARCHAR(20),
foreign key (PATIENT_ID) references PATIENTS(PATIENT_ID),
APPOINTMENT_DATE DATE,
DOCTER_ID VARCHAR(10),
foreign key (DOCTER_ID) references DOCTERS(DOCTER_ID),
SERVICE_TYPE VARCHAR(30),
PRIORITY VARCHAR(10),
ESTIMATED_COST DECIMAL(10,2) NOT NULL,
BOOKING_CHANEL VARCHAR(20)
);
SELECT * FROM APPOINTMENTS;

#TABLE 5. {TREATMENTS}
CREATE TABLE TREATMENTS
(
TREATMENT_ID VARCHAR(20) PRIMARY KEY,
APPOINTMENT_ID VARCHAR(20),
foreign key (APPOINTMENT_ID) references APPOINTMENTS(APPOINTMENT_ID),
DOCTER_ID VARCHAR(10),
foreign key (DOCTER_ID) references DOCTERS(DOCTER_ID),
ROOM_ID VARCHAR(10),
foreign key (ROOM_ID) references ROOMS(ROOM_ID),
ACTUAL_TREATMENT_DATE DATE NOT NULL,
STATUS VARCHAR(20) NOT NULL,
TREATMENT_ATTEMPT INT,
TREATMENT_DURATION_MIN INT,
WAITING_TIME_MIN INT,
TREATMENT_COST DECIMAL(10,2) NOT NULL
);
SELECT * FROM TREATMENTS;

