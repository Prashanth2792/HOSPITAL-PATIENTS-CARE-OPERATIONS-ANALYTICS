-- 4.3 Evaluate Treatment Performance --
-- ● Compare treatment outcomes across cities. --
-- Find out how treatment outcomes differ from one city to another.
SELECT P.CITY, T.STATUS,
COUNT(T.TREATMENT_ID) AS TREATMENT_COUNT
